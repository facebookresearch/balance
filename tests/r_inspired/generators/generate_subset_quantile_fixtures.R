args<-commandArgs(trailingOnly=TRUE);root<-args[[1]];out<-args[[2]]
library(matrixStats)
fmt<-function(d){for(n in names(d))if(is.double(d[[n]]))d[[n]]<-sprintf('%.17g',d[[n]]);d}
write17<-function(d,n)write.csv(fmt(d),file.path(out,n),row.names=FALSE)
set.seed(1)
e<-new.env();old<-setwd(file.path(root,'third-party/R/matrixStats/tests'))
source('weightedMean_subset.R',local=e);setwd(old)
# Exact repeated-index case from validateIndicesFramework.R; zero R indices
# select nothing. Inputs are those generated by the actual upstream test run.
idx<-c(3,0,0,5,1,5,5)
expected<-weightedMean(e$x,w=e$w,idxs=idx)
write17(data.frame(value=e$x,weight=e$w),'matrixstats_subset_inputs.csv')
write17(data.frame(expected=expected),'matrixstats_subset_expected.csv')
library(survey);data(api)
d<-svydesign(id=~dnum,weights=~pw,data=apiclus1,fpc=~fpc)
p<-c(.2,.5,.9)
q<-as.numeric(coef(svyquantile(~ell,d,p,qrule='hf2',ci=FALSE)))
stopifnot(isTRUE(all.equal(q,as.numeric(quantile(apiclus1$ell,p,type=2)))))
write17(data.frame(value=apiclus1$ell,weight=apiclus1$pw),'survey_quantile_inputs.csv')
write17(data.frame(probability=p,expected=q),'survey_quantile_expected.csv')
